"""PostgreSQL schema setup: what the models cannot declare.

A fresh PostgreSQL database is not built by replaying the Alembic history - those
revisions were written for SQLite. It is created from the models
(``Base.metadata.create_all``), then this module adds the objects that live
outside the models, then it is stamped at head. Every revision after that has to
run on both databases.

The objects added here:

* the ``grimoire`` text search configuration - English stemming, accents folded,
  no stopwords - so page search behaves like SQLite's ``porter unicode61`` FTS5
  tokenizer: ``café`` finds ``cafe`` and a search for ``the`` still matches;
* ``book_pages`` with a generated ``tsvector`` column and its GIN index, the
  PostgreSQL counterpart of ``book_pages`` + the ``book_search`` FTS5 index
  (markup-like text is indexed as plain words, see ``MARKUP_CHARS``);
* ``content_search``, the character-builder catalogue index, likewise;
* the case-insensitive unique index on ``users`` (``usernames.ensure_unique_index``);
* the default lookup rows (genres, system families, licenses, dice materials)
  that SQLite gets from migrations 0004 and 0006.

Every statement is idempotent, so running it again is harmless.
"""
import logging
import uuid
from typing import Any

from sqlalchemy import String, text
from sqlalchemy.ext.compiler import compiles

logger = logging.getLogger("grimoire.db")

SEARCH_CONFIG = "grimoire"


@compiles(String, "postgresql")
def _varchar_without_length(type_: Any, compiler: Any, **kw: Any) -> str:
    """``String(n)`` as an unbounded VARCHAR on PostgreSQL.

    SQLite never enforced the lengths on the models, so libraries hold titles,
    paths and metadata longer than them. Enforcing them only on PostgreSQL would
    make the same data fail to save there - or fail part-way through a migration
    from SQLite. An unbounded VARCHAR costs nothing extra in PostgreSQL.
    """
    collation = f' COLLATE "{type_.collation}"' if type_.collation else ""
    return "VARCHAR" + collation

# Text beyond this many characters of one page is stored but not indexed. A
# tsvector is capped at 1 MB, and a page past this length would fail to insert
# rather than index; no real page comes near it.
INDEXED_CHARS = 250_000

# Characters that open what PostgreSQL's text search parser takes for markup:
# "<" an XML tag, "&" an entity. The parser drops a whole tag - "<goblin king>" -
# and an entity - "&amp;" - where SQLite's FTS5 tokenizer just splits on the
# punctuation and indexes the words. Both are swapped for a space before the
# text is parsed, in the index and in every search term (services.pg_search), so
# the same words are found on both databases.
MARKUP_CHARS = "<&"


def searchable(expr: str) -> str:
    """SQL for the text ``expr`` with ``MARKUP_CHARS`` turned into spaces."""
    return f"translate({expr}, '{MARKUP_CHARS}', '{' ' * len(MARKUP_CHARS)}')"


def book_pages_search_sql() -> str:
    """The ``book_pages.search`` generation expression."""
    return (
        f"to_tsvector('{SEARCH_CONFIG}'::regconfig, "
        f"{searchable(f'left(content, {INDEXED_CHARS})')})"
    )


def content_search_sql() -> str:
    """The ``content_search.search`` generation expression."""
    text_sql = f"left(coalesce(name, '') || ' ' || coalesce(body, ''), {INDEXED_CHARS})"
    return f"to_tsvector('{SEARCH_CONFIG}'::regconfig, {searchable(text_sql)})"


_TEXT_SEARCH = (
    # Trusted since PostgreSQL 13: the database owner can create it, no superuser.
    "CREATE EXTENSION IF NOT EXISTS unaccent",
    f"""
    DO $$ BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_ts_dict WHERE dictname = '{SEARCH_CONFIG}_stem') THEN
            -- Snowball English with no StopWords file: every word is indexed.
            CREATE TEXT SEARCH DICTIONARY {SEARCH_CONFIG}_stem (
                TEMPLATE = snowball, Language = english
            );
        END IF;
        IF NOT EXISTS (SELECT 1 FROM pg_ts_config WHERE cfgname = '{SEARCH_CONFIG}') THEN
            CREATE TEXT SEARCH CONFIGURATION {SEARCH_CONFIG} (COPY = simple);
            ALTER TEXT SEARCH CONFIGURATION {SEARCH_CONFIG}
                ALTER MAPPING FOR asciiword, asciihword, hword_asciipart,
                                  word, hword, hword_part
                WITH unaccent, {SEARCH_CONFIG}_stem;
        END IF;
    END $$
    """,
)

_TABLES = (
    f"""
    CREATE TABLE IF NOT EXISTS book_pages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        book_id TEXT NOT NULL,
        page_number INTEGER NOT NULL,
        content TEXT NOT NULL,
        search tsvector GENERATED ALWAYS AS ({book_pages_search_sql()}) STORED
    )
    """,
    "CREATE INDEX IF NOT EXISTS ix_book_pages_book_page ON book_pages (book_id, page_number)",
    "CREATE INDEX IF NOT EXISTS ix_book_pages_search ON book_pages USING GIN (search)",
    f"""
    CREATE TABLE IF NOT EXISTS content_search (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        entry_row TEXT,
        pack_row TEXT,
        schema_id TEXT,
        content_type TEXT,
        name TEXT,
        body TEXT,
        search tsvector GENERATED ALWAYS AS ({content_search_sql()}) STORED
    )
    """,
    "CREATE INDEX IF NOT EXISTS ix_content_search_pack ON content_search (pack_row)",
    "CREATE INDEX IF NOT EXISTS ix_content_search_type "
    "ON content_search (schema_id, content_type)",
    "CREATE INDEX IF NOT EXISTS ix_content_search_search ON content_search USING GIN (search)",
)


def create_schema(conn: Any, *, seed: bool = True) -> None:
    """Everything a fresh PostgreSQL database needs, short of the Alembic stamp.

    ``seed=False`` leaves the lookup tables empty, for the SQLite migration
    command, which copies the install's own lookup rows instead.
    """
    from . import Base  # noqa: F401 - every model module registered on Base.metadata
    from ..usernames import ensure_unique_index

    Base.metadata.create_all(conn)
    create_search_objects(conn)
    ensure_unique_index(conn)
    if seed:
        seed_lookups(conn)


def create_search_objects(conn: Any) -> None:
    """The text search configuration and the two search tables. Idempotent."""
    for statement in _TEXT_SEARCH + _TABLES:
        conn.execute(text(statement))


def seed_lookups(conn: Any) -> None:
    """The default lookup rows SQLite gets from migrations 0004 and 0006.

    Skips any name already present, so it is safe to repeat.
    """
    from ..migrations._frozen.lookup_defaults import (
        DEFAULT_DICE_MATERIALS,
        DEFAULT_GENRES,
        DEFAULT_LICENSES,
        DEFAULT_PARENT_SYSTEMS,
        DEFAULT_SYSTEM_FAMILIES,
    )

    def names(table: str) -> set:
        return {r[0] for r in conn.execute(text(f"SELECT name FROM {table}"))}

    def insert(table: str, name: str, order: int, **extra: Any) -> str:
        new_id = str(uuid.uuid4())
        columns = ", ".join(f'"{c}"' for c in extra)
        values = ", ".join(f":{c}" for c in extra)
        conn.execute(
            text(
                f"INSERT INTO {table} (id, name, is_default, sort_order"
                f"{', ' + columns if extra else ''}) "
                f"VALUES (:id, :name, TRUE, :order{', ' + values if extra else ''})"
            ),
            {"id": new_id, "name": name, "order": order, **extra},
        )
        return new_id

    genres = names("genres")
    for order, (name, children) in enumerate(DEFAULT_GENRES, start=1):
        if name in genres:
            parent_id = conn.execute(
                text("SELECT id FROM genres WHERE name = :n"), {"n": name}
            ).scalar()
        else:
            parent_id = insert("genres", name, order, parent_id=None)
            genres.add(name)
        for child_order, (child, _grandchildren) in enumerate(children, start=1):
            if child not in genres:
                insert("genres", child, child_order, parent_id=parent_id)
                genres.add(child)

    for table, defaults in (
        ("system_families", DEFAULT_SYSTEM_FAMILIES),
        ("parent_systems", DEFAULT_PARENT_SYSTEMS),
        ("licenses", DEFAULT_LICENSES),
    ):
        present = names(table)
        for order, name in enumerate(defaults):
            if name not in present:
                insert(table, name, order)

    present = names("dice_materials")
    for order, (group, name) in enumerate(DEFAULT_DICE_MATERIALS):
        if name not in present:
            insert("dice_materials", name, order, group=group)
